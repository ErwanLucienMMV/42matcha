CREATE TABLE accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(30) NOT NULL,
    email VARCHAR(254) NOT NULL,
    first_name VARCHAR(80) NOT NULL,
    last_name VARCHAR(80) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    verified BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_seen TIMESTAMPTZ,
    CHECK (username ~ '^[a-zA-Z0-9_]{3,30}$')
);
CREATE UNIQUE INDEX accounts_username_unique ON accounts (LOWER(username));
CREATE UNIQUE INDEX accounts_email_unique ON accounts (LOWER(email));

CREATE TABLE profiles (
    user_id BIGINT PRIMARY KEY REFERENCES accounts(id) ON DELETE CASCADE,
    gender VARCHAR(16) CHECK (gender IN ('woman', 'man', 'nonbinary')),
    orientation VARCHAR(16) NOT NULL DEFAULT 'bisexual' CHECK (orientation IN ('bisexual', 'heterosexual', 'homosexual')),
    birth_date DATE,
    biography VARCHAR(2000) NOT NULL DEFAULT '',
    city VARCHAR(120) NOT NULL DEFAULT '',
    latitude DOUBLE PRECISION CHECK (latitude BETWEEN -90 AND 90),
    longitude DOUBLE PRECISION CHECK (longitude BETWEEN -180 AND 180),
    gps_consent BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK ((latitude IS NULL) = (longitude IS NULL))
);
CREATE INDEX profiles_location ON profiles (latitude, longitude);
CREATE INDEX profiles_age ON profiles (birth_date);

CREATE TABLE tags (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(40) NOT NULL UNIQUE,
    CHECK (name ~ '^[a-z0-9][a-z0-9_-]{0,39}$')
);
CREATE TABLE profile_tags (
    user_id BIGINT NOT NULL REFERENCES profiles(user_id) ON DELETE CASCADE,
    tag_id BIGINT NOT NULL REFERENCES tags(id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, tag_id)
);
CREATE INDEX profile_tags_reverse ON profile_tags (tag_id, user_id);

CREATE TABLE photos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES profiles(user_id) ON DELETE CASCADE,
    content BYTEA NOT NULL CHECK (OCTET_LENGTH(content) BETWEEN 1 AND 5242880),
    media_type VARCHAR(32) NOT NULL CHECK (media_type IN ('image/jpeg', 'image/png')),
    is_primary BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX photos_one_primary ON photos (user_id) WHERE is_primary;
CREATE INDEX photos_owner ON photos (user_id);
CREATE FUNCTION enforce_photo_limit() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    PERFORM user_id FROM profiles WHERE user_id = NEW.user_id FOR UPDATE;
    IF (SELECT COUNT(*) FROM photos WHERE user_id = NEW.user_id AND id <> NEW.id) >= 5 THEN
        RAISE EXCEPTION 'A profile may have at most five photos' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER photos_limit BEFORE INSERT OR UPDATE OF user_id ON photos
    FOR EACH ROW EXECUTE FUNCTION enforce_photo_limit();

CREATE TABLE account_tokens (
    token_hash CHAR(64) PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    purpose VARCHAR(20) NOT NULL CHECK (purpose IN ('verify', 'reset', 'email_change')),
    new_email VARCHAR(254),
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX account_tokens_owner ON account_tokens (user_id, purpose);

CREATE TABLE sessions (
    token_hash CHAR(64) PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    csrf_hash CHAR(64) NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    last_seen TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX sessions_owner ON sessions (user_id);
CREATE INDEX sessions_expiration ON sessions (expires_at);

CREATE TABLE likes (
    actor_id BIGINT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    target_id BIGINT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (actor_id, target_id),
    CHECK (actor_id <> target_id)
);
CREATE INDEX likes_received ON likes (target_id, actor_id);

CREATE TABLE visits (
    visitor_id BIGINT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    target_id BIGINT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    visited_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (visitor_id, target_id),
    CHECK (visitor_id <> target_id)
);
CREATE INDEX visits_received ON visits (target_id, visited_at DESC);

CREATE TABLE blocks (
    actor_id BIGINT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    target_id BIGINT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (actor_id, target_id),
    CHECK (actor_id <> target_id)
);
CREATE INDEX blocks_reverse ON blocks (target_id, actor_id);

CREATE TABLE reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id BIGINT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    target_id BIGINT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    reason VARCHAR(1000) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (reporter_id <> target_id),
    UNIQUE (reporter_id, target_id)
);

CREATE TABLE notification_suppressions (
    recipient_id BIGINT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    actor_id BIGINT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    PRIMARY KEY (recipient_id, actor_id)
);

CREATE TABLE messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id BIGINT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    recipient_id BIGINT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    body VARCHAR(4000) NOT NULL CHECK (LENGTH(TRIM(body)) > 0),
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (sender_id <> recipient_id)
);
CREATE INDEX messages_pair ON messages (sender_id, recipient_id, id DESC);
CREATE INDEX messages_recipient ON messages (recipient_id, is_read, id DESC);

CREATE TABLE notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id BIGINT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    actor_id BIGINT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    kind VARCHAR(16) NOT NULL CHECK (kind IN ('like', 'visit', 'message', 'connection', 'unlike')),
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (recipient_id <> actor_id)
);
CREATE INDEX notifications_recipient ON notifications (recipient_id, id DESC);
CREATE INDEX notifications_unread ON notifications (recipient_id) WHERE NOT is_read;

CREATE TABLE mail_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient VARCHAR(254) NOT NULL,
    subject VARCHAR(200) NOT NULL,
    body TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    sent_at TIMESTAMPTZ,
    attempts INTEGER NOT NULL DEFAULT 0
);
